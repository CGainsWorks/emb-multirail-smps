def template(path: Path) -> None:
    text = ("(kicad_pcb\n\t(version 20240108)\n\t(generator \"pcbnew\")\n"
            "\t(generator_version \"8.0\")\n\t(general\n\t\t(thickness 1.695)\n"
            "\t\t(legacy_teardrops no)\n\t)\n\t(paper \"A4\")\n"
            "\t(title_block\n\t\t(title \"Multi-rail switch-mode power supply\")\n"
            "\t\t(date \"2026-10-16\")\n\t\t(rev \"A\")\n\t\t(company \"CGainsWorks\")\n"
            "\t\t(comment 1 \"Placed by scripts/kicad/gen_pcb.py, routed by Freerouting\")\n"
            "\t\t(comment 2 \"Not fabricated, not assembled, not measured\")\n\t)"
            + STACKUP + "\t(net 0 \"\")\n)\n")
    path.write_text(text, encoding="utf-8")


def read_netlist(path: Path):
    top = parse(path.read_text(encoding="utf-8"))[0]
    comps = {}
    for comp in find_all(find(top, "components"), "comp"):
        ref = unq(find(comp, "ref")[1])
        sheet = unq(find(find(comp, "sheetpath"), "tstamps")[1])
        comps[ref] = {"value": unq(find(comp, "value")[1]),
                      "footprint": unq(find(comp, "footprint")[1]),
                      "path": sheet + unq(find(comp, "tstamps")[1]),
                      "sheetname": unq(find(find(comp, "sheetpath"), "names")[1])}
    pads = {}
    for net in find_all(find(top, "nets"), "net"):
        name = unq(find(net, "name")[1])
        for node in find_all(net, "node"):
            pads[(unq(find(node, "ref")[1]), unq(find(node, "pin")[1]))] = name
    return comps, pads


def courtyard(fp) -> tuple[float, float, float, float]:
    box = fp.GetCourtyard(pcbnew.F_CrtYd).BBox()
    if box.GetWidth() == 0:
        box = fp.GetBoundingBox(False, False)
    return (pcbnew.ToMM(box.GetLeft()), pcbnew.ToMM(box.GetTop()),
            pcbnew.ToMM(box.GetRight()), pcbnew.ToMM(box.GetBottom()))


def place(args) -> int:
    comps, pads = read_netlist(Path(args.netlist))
    # Load the empty board from its final name, so KiCad picks up the
    # project file next to it and the net classes reach the DSN export.
    out = Path(args.out)
    pro = out.with_suffix(".kicad_pro")
    pro_text = pro.read_text(encoding="utf-8")
    template(out)
    board = pcbnew.LoadBoard(str(out))

    nets = {}
    for name in sorted(set(pads.values())):
        n = pcbnew.NETINFO_ITEM(board, name)
        board.Add(n)
        nets[name] = n

    fps = {}
    for ref, c in sorted(comps.items()):
        if ref.startswith("#"):
            continue
        lib, name = c["footprint"].split(":")
        fp = pcbnew.FootprintLoad(str(FP_DIR / f"{lib}.pretty"), name)
        if fp is None:
            raise SystemExit(f"{ref}: footprint {c['footprint']} not found")
        fp.SetFPID(pcbnew.LIB_ID(lib, name))
        fp.SetReference(ref)
        fp.SetValue(c["value"])
        fp.SetPath(pcbnew.KIID_PATH(c["path"]))
        fp.SetSheetname(c["sheetname"].strip("/"))
        fp.SetSheetfile(f"{c['sheetname'].strip('/')}.kicad_sch")
        board.Add(fp)
        for pad in fp.Pads():
            net = pads.get((ref, pad.GetNumber()))
            if net in nets:
                pad.SetNet(nets[net])
        fps[ref] = fp

    for ref, (x, y, rot) in FIXED.items():
        fps[ref].SetOrientationDegrees(rot)
        fps[ref].SetPosition(pcbnew.VECTOR2I(MM(X0 + x), MM(Y0 + y)))

    placed = set(FIXED)
    for region, ((rx0, ry0, rx1, ry1), rows) in REGIONS.items():
        sizes = {}
        for row in rows:
            for ref in row:
                fps[ref].SetPosition(pcbnew.VECTOR2I(0, 0))
                sizes[ref] = courtyard(fps[ref])
        heights = [max(sizes[r][3] - sizes[r][1] for r in row) for row in rows]
        gap_y = (ry1 - ry0 - sum(heights)) / (len(rows) + 1)
        if gap_y < 0.5:
            raise SystemExit(f"region {region} is too short")
        y = ry0 + gap_y
        for row, h in zip(rows, heights):
            widths = [sizes[r][2] - sizes[r][0] for r in row]
            gap_x = (rx1 - rx0 - sum(widths)) / (len(row) + 1)
            if gap_x < 0.5:
                raise SystemExit(f"region {region} row {row} is too wide")
            x = rx0 + gap_x
            for ref, w in zip(row, widths):
                l, t, r, b = sizes[ref]
                # Centre each part vertically in its row.
                yc = y + (h - (b - t)) / 2
                fps[ref].SetPosition(pcbnew.VECTOR2I(MM(X0 + x - l), MM(Y0 + yc - t)))
                x += w + gap_x
                placed.add(ref)
            y += h + gap_y
    missing = set(fps) - placed
    if missing:
        raise SystemExit(f"parts with no place: {sorted(missing)}")

    # Edge cuts.
    pts = [(0, 0), (W, 0), (W, H), (0, H)]
    for (ax, ay), (bx, by) in zip(pts, pts[1:] + pts[:1]):
        seg = pcbnew.PCB_SHAPE(board)
        seg.SetShape(pcbnew.SHAPE_T_SEGMENT)
        seg.SetLayer(pcbnew.Edge_Cuts)
        seg.SetWidth(MM(0.1))
        seg.SetStart(pcbnew.VECTOR2I(MM(X0 + ax), MM(Y0 + ay)))
        seg.SetEnd(pcbnew.VECTOR2I(MM(X0 + bx), MM(Y0 + by)))
        board.Add(seg)

    def net(short):
        found = [n for k, n in nets.items() if k.rsplit("/", 1)[-1] == short]
        if len(found) != 1:
            raise SystemExit(f"net {short}: {len(found)} matches")
        return found[0]

    add_zone(board, net("GND"), pcbnew.In1_Cu,
             [(0.5, 0.5), (W - 0.5, 0.5), (W - 0.5, H - 0.5), (0.5, H - 0.5)], 0)
    planes = {"GND": [add_zone(board, net("GND"), pcbnew.In1_Cu,
                               [(0, 0), (W, 0), (W, H), (0, H)], 0, keep=False)]}
    for name, poly in POWER_PLANES:
        planes.setdefault(name, []).append(add_zone(board, net(name), pcbnew.In2_Cu, poly, 0))
    add_thermal_vias(board)
    fanout(board, planes)

    board.Save(args.out)
    pro.write_text(pro_text, encoding="utf-8")   # Save rewrites it
    if args.dsn:
        if not pcbnew.ExportSpecctraDSN(board, args.dsn):
            raise SystemExit("DSN export failed")
    print(f"placed {len(fps)} footprints, {len(nets)} nets")
    return 0


def add_zone(board, net, layer, poly, priority, clearance=0.3, keep=True):
    """A copper zone. With ``keep`` false it is only a shape to test against
    and is not added to the board."""
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    z.SetNetCode(net.GetNetCode())
    outline = z.Outline()
    outline.NewOutline()
    for x, y in poly:
        outline.Append(MM(X0 + x), MM(Y0 + y))
    z.SetAssignedPriority(priority)
    z.SetLocalClearance(MM(clearance))
    z.SetMinThickness(MM(0.25))
    z.SetThermalReliefGap(MM(0.3))
    z.SetThermalReliefSpokeWidth(MM(0.4))
    z.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
    if keep:
        board.Add(z)
    return z


def fanout(board, planes, via_dia=0.6, drill=0.3):
    """Drop a via beside every surface mount pad on a plane net.

    Ground goes to In1 and VIN, +5V and +3V3 to their pours on In2. Doing this
    before the autorouter runs means it sees those pins as already joined
    through the planes, which is how the board is meant to work and spends
    its effort on the signals. Each via is placed at the nearest spot round
    its pad that clears every other net's copper, with a short stub of track.
    """
    clear = POWER_CLEARANCE_TOP
    pads = [pad for fp in board.GetFootprints() for pad in fp.Pads()]
    obstacles = []          # (x, y, radius, netcode) for vias already placed
    for t in board.GetTracks():
        if t.GetClass() == "PCB_VIA":
            obstacles.append((pcbnew.ToMM(t.GetPosition().x), pcbnew.ToMM(t.GetPosition().y),
                              via_dia / 2, t.GetNetCode()))
    stubs = []
    edge = (X0 + 1.0, Y0 + 1.0, X0 + W - 1.0, Y0 + H - 1.0)

    def short(pad):
        return pad.GetNetname().rsplit("/", 1)[-1]

    def free(x, y, seg_from, netcode, stub_width=0.3):
        if not (edge[0] < x < edge[2] and edge[1] < y < edge[3]):
            return False
        via = pcbnew.SHAPE_CIRCLE(pcbnew.VECTOR2I(MM(x), MM(y)), MM(via_dia / 2))
        seg = pcbnew.SHAPE_SEGMENT(seg_from, pcbnew.VECTOR2I(MM(x), MM(y)), MM(stub_width))
        for pad in pads:
            if pad.GetNetCode() == netcode:
                continue
            for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
                if not pad.IsOnLayer(layer):
                    continue
                sh = pad.GetEffectiveShape(layer)
                if sh.Collide(via, MM(clear)) or (layer == pcbnew.F_Cu
                                                   and sh.Collide(seg, MM(clear))):
                    return False
        for ox, oy, r, code in obstacles:
            need = r + via_dia / 2 + (0.25 if code == netcode else clear + 0.05)
            if (ox - x) ** 2 + (oy - y) ** 2 < need ** 2:
                return False
        for a, b, code in stubs:
            if code == netcode:
                continue
            other = pcbnew.SHAPE_SEGMENT(a, b, MM(0.3))
            if other.Collide(via, MM(clear)) or other.Collide(seg, MM(clear)):
                return False
        return True

    count = [0]

    def add(pad, c, x, y, width):
        via = pcbnew.PCB_VIA(board)
        via.SetPosition(pcbnew.VECTOR2I(MM(x), MM(y)))
        via.SetDrill(MM(drill))
        via.SetWidth(MM(via_dia))
        via.SetNet(pad.GetNet())
        board.Add(via)
        tr = pcbnew.PCB_TRACK(board)
        tr.SetStart(c)
        tr.SetEnd(pcbnew.VECTOR2I(MM(x), MM(y)))
        tr.SetWidth(MM(width))
        tr.SetLayer(pcbnew.F_Cu)
        tr.SetNet(pad.GetNet())
        board.Add(tr)
        obstacles.append((x, y, via_dia / 2, pad.GetNetCode()))
        stubs.append((c, pcbnew.VECTOR2I(MM(x), MM(y)), pad.GetNetCode()))
        count[0] += 1

    for pad in pads:
        name = short(pad)
        if name not in planes or pad.GetAttribute() != pcbnew.PAD_ATTRIB_SMD:
            continue
        if any(t.GetClass() == "PCB_VIA" and pad.HitTest(t.GetPosition())
               for t in board.GetTracks()):
            continue            # an exposed pad that already has thermal vias
        c = pad.GetPosition()
        if pad.GetParentAsString().startswith("U"):
            # Fine pitch pin: a stub straight out of the package, then a via.
            fp_c = pad.GetParent().GetPosition()
            dx, dy = c.x - fp_c.x, c.y - fp_c.y
            ux, uy = (1 if dx > 0 else -1, 0) if abs(dx) > abs(dy) else (0, 1 if dy > 0 else -1)
            bb = pad.GetBoundingBox()
            reach = (pcbnew.ToMM(bb.GetWidth()) if ux else pcbnew.ToMM(bb.GetHeight())) / 2
            cx, cy = pcbnew.ToMM(c.x), pcbnew.ToMM(c.y)
            for length in (0.9, 1.4, 1.9, 2.4):
                x, y = cx + ux * (reach + length), cy + uy * (reach + length)
                inside = any(z.Outline().Contains(pcbnew.VECTOR2I(MM(x), MM(y)))
                             for z in planes[name])
                if inside and free(x, y, c, pad.GetNetCode(), stub_width=0.25):
                    add(pad, c, x, y, 0.25)
                    break
            else:
                print(f"no escape for {pad.GetParentAsString()} pad {pad.GetNumber()}, "
                      "left to the router")
            continue
        cx, cy = pcbnew.ToMM(c.x), pcbnew.ToMM(c.y)
        bb = pad.GetBoundingBox()
        half = max(pcbnew.ToMM(bb.GetWidth()), pcbnew.ToMM(bb.GetHeight())) / 2
        done = False
        for extra in (0.0, 0.3, 0.6, 1.0, 1.5, 2.0):
            d = half + via_dia / 2 + 0.2 + extra
            for k in range(16):
                import math
                ang = 2 * math.pi * k / 16
                x, y = cx + d * math.cos(ang), cy + d * math.sin(ang)
                inside = any(z.Outline().Contains(pcbnew.VECTOR2I(MM(x), MM(y)))
                             for z in planes[name])
                if not inside or not free(x, y, c, pad.GetNetCode()):
                    continue
                add(pad, c, x, y, 0.3)
                done = True
                break
            if done:
                break
        if not done:
            print(f"no room for a plane via at {pad.GetParentAsString()} pad {pad.GetNumber()}")
    print(f"{count[0]} plane vias")


def add_thermal_vias(board, drill=0.3, dia=0.6, pitch=1.2):
    """0.30 mm vias on a grid inside every exposed ground pad, which is what
    docs/stackup.md asks for. The library's own thermal via footprints use
    0.20 mm drills, below the fabrication minimum, so they are not used."""
    count = 0
    for fp in board.GetFootprints():
        if not fp.GetReference().startswith("U"):
            continue
        for pad in fp.Pads():
            if pad.GetNetname().rsplit("/", 1)[-1] != "GND":
                continue
            bb = pad.GetBoundingBox()
            w, h = pcbnew.ToMM(bb.GetWidth()), pcbnew.ToMM(bb.GetHeight())
            if min(w, h) < dia + 0.2:
                continue
            nx = max(1, int((w - dia) // pitch) + 1)
            ny = max(1, int((h - dia) // pitch) + 1)
            cx, cy = pcbnew.ToMM(bb.GetCenter().x), pcbnew.ToMM(bb.GetCenter().y)
            for i in range(nx):
                for j in range(ny):
                    x = cx + (i - (nx - 1) / 2) * pitch
                    y = cy + (j - (ny - 1) / 2) * pitch
                    via = pcbnew.PCB_VIA(board)
                    via.SetPosition(pcbnew.VECTOR2I(MM(x), MM(y)))
                    via.SetDrill(MM(drill))
                    via.SetWidth(MM(dia))
                    via.SetNet(pad.GetNet())
                    board.Add(via)
                    count += 1
    print(f"{count} thermal vias under exposed pads")


POWER_WIDTHS = (2.0, 1.5, 1.2, 1.0, 0.8, 0.6, 0.5, 0.4, 0.3)


def widen_power(board) -> None:
    """Widen every power track segment as far as clearance allows.

    The autorouter lays power at 0.25 mm so it can reach fine pitch pins.
    Away from those pins there is usually room and on 2 oz copper the width
    is what sets how much current a track carries, so each segment is tried
    at a series of widths and kept at the widest that clears every other
    net's copper on its layer by the power clearance. Segments are revisited
    until nothing changes, because widening one can be blocked by another
    that has not been widened yet only on the same net, which is allowed.
    """
    power = {n for n, nc in ((t.GetNetname(), t.GetNetClassName())
                             for t in board.GetTracks()) if nc == "Power"}
    tracks = [t for t in board.GetTracks()
              if t.GetClass() == "PCB_TRACK" and t.GetNetname() in power]
    items = []
    for fp in board.GetFootprints():
        for pad in fp.Pads():
            items.append(pad)
    items += [t for t in board.GetTracks()]
    edge = board.GetBoardEdgesBoundingBox()
    widened = 0
    for t in tracks:
        layer = t.GetLayer()
        others = [o for o in items if o is not t and o.GetNetCode() != t.GetNetCode()
                  and o.IsOnLayer(layer)]
        a, b = t.GetStart(), t.GetEnd()
        lo = min(a.x, b.x), min(a.y, b.y)
        hi = max(a.x, b.x), max(a.y, b.y)
        near = []
        reach = MM(max(POWER_WIDTHS) + POWER_CLEARANCE_TOP + 3)
        for o in others:
            bb = o.GetBoundingBox()
            if (bb.GetRight() < lo[0] - reach or bb.GetLeft() > hi[0] + reach
                    or bb.GetBottom() < lo[1] - reach or bb.GetTop() > hi[1] + reach):
                continue
            near.append(o.GetEffectiveShape(layer))
        for w in POWER_WIDTHS:
            if MM(w) <= t.GetWidth():
                break
            seg = pcbnew.SHAPE_SEGMENT(a, b, MM(w))
            margin = MM(w / 2 + 0.3)
            if (min(a.x, b.x) - margin < edge.GetLeft() or max(a.x, b.x) + margin > edge.GetRight()
                    or min(a.y, b.y) - margin < edge.GetTop()
                    or max(a.y, b.y) + margin > edge.GetBottom()):
                continue
            if any(sh.Collide(seg, MM(POWER_CLEARANCE_TOP)) for sh in near):
                continue
            t.SetWidth(MM(w))
            widened += 1
            break
    print(f"widened {widened} of {len(tracks)} power track segments")


def finish(args) -> int:
    board = pcbnew.LoadBoard(args.board)
    if args.ses:
        if not pcbnew.ImportSpecctraSES(board, args.ses):
            raise SystemExit("SES import failed")
    gnd = board.FindNet("GND")
    full = [(0.5, 0.5), (W - 0.5, 0.5), (W - 0.5, H - 0.5), (0.5, H - 0.5)]
    have = {(z.GetLayer(), z.GetNetname()) for z in board.Zones()}
    for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
        if (layer, "GND") not in have:
            add_zone(board, gnd, layer, full, 0, clearance=0.3)
    if not args.no_widen:
        widen_power(board)
    filler = pcbnew.ZONE_FILLER(board)
    filler.Fill(board.Zones())
    pro = Path(args.board).with_suffix(".kicad_pro")
    pro_text = pro.read_text(encoding="utf-8")
    board.Save(args.board)
    pro.write_text(pro_text, encoding="utf-8")
    tracks = [t for t in board.GetTracks()]
    vias = [t for t in tracks if t.GetClass() == "PCB_VIA"]
    print(f"{len(tracks) - len(vias)} track segments, {len(vias)} vias")
    return 0


def rip(args) -> int:
    """Take up the routing the DRC objects to, ready for another router pass.

    Freerouting occasionally leaves two nets touching where it could not
    finish a connection cleanly. Every track named in a short, clearance or
    crossing violation is removed, with the rest of its net's track within
    2 mm, and the outer layer pours come off so the router can see the board.
    The next pass routes what is now missing, around what stays.
    """
    import json
    import math
    board = pcbnew.LoadBoard(args.board)
    drc = json.loads(Path(args.drc).read_text(encoding="utf-8"))
    spots = []
    for v in drc["violations"]:
        if v["severity"] != "error" or v["type"] not in (
                "shorting_items", "clearance", "tracks_crossing", "hole_clearance"):
            continue
        for item in v["items"]:
            obj = board.GetItem(pcbnew.KIID(item["uuid"]))
            obj = obj.Cast() if obj is not None else None
            if obj is not None and obj.GetClass() in ("PCB_TRACK", "PCB_VIA", "PCB_ARC"):
                spots.append((item["pos"]["x"], item["pos"]["y"], obj.GetNetCode()))
    doomed = {}
    for t in board.GetTracks():
        for x, y, code in spots:
            if t.GetNetCode() != code:
                continue
            for pt in (t.GetStart(), t.GetEnd()):
                if math.hypot(pcbnew.ToMM(pt.x) - x, pcbnew.ToMM(pt.y) - y) < 2.0:
                    doomed[t.m_Uuid.AsString()] = t
    for t in doomed.values():
        board.Remove(t)
    for z in list(board.Zones()):
        if z.GetLayer() in (pcbnew.F_Cu, pcbnew.B_Cu):
            board.Remove(z)
        else:
            z.UnFill()
    pro = Path(args.board).with_suffix(".kicad_pro")
    pro_text = pro.read_text(encoding="utf-8")
    board.Save(args.board)
    pro.write_text(pro_text, encoding="utf-8")
    if not pcbnew.ExportSpecctraDSN(board, args.dsn):
        raise SystemExit("DSN export failed")
    print(f"removed {len(doomed)} track pieces at {len(spots)} violations")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("place")
    p.add_argument("--netlist", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--dsn")
    f = sub.add_parser("finish")
    f.add_argument("--board", required=True)
    f.add_argument("--ses")
    f.add_argument("--no-widen", action="store_true")
    r = sub.add_parser("rip")
    r.add_argument("--board", required=True)
    r.add_argument("--drc", required=True)
    r.add_argument("--dsn", required=True)
    args = ap.parse_args()
    return {"place": place, "finish": finish, "rip": rip}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
