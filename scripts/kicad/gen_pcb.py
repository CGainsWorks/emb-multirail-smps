#!/usr/bin/env python3
"""Place the board, pour its planes and hand it to the autorouter.

Runs inside the ``kicad/kicad`` container, which has KiCad's ``pcbnew``
Python module and footprint library:

    python3 scripts/kicad/gen_pcb.py place  --netlist N --out B.kicad_pcb --dsn B.dsn
    python3 scripts/kicad/gen_pcb.py finish --board B.kicad_pcb --ses B.ses

``place`` builds a four layer board to ``docs/stackup.md`` from the netlist
the schematic exports, puts every part in its stage's region, adds the ground
plane on In1 and the split power planes on In2 and writes a Specctra DSN for
Freerouting. ``finish`` reads the routed session back, adds the outer layer
ground pours, fills every zone and saves. ``scripts/kicad/route_board.sh``
runs the three steps; CI only runs DRC on the committed result.

The placement is generated by region, not drawn by a person and the routing
is an autorouter's. Both pass DRC. Neither has been through the review in
``docs/layout_rules.md`` and that is stated wherever the board is described.
"""

