def spec_markdown() -> str:
    rail_rows = [{
        "rail": r.name,
        "topology": r.topology,
        "control": r.control,
        "source": r.source,
        "Vout [V]": r.v_out_v,
        "Iout total [A]": r.i_max_a,
        "at connector [A]": r.i_external_a,
        "ripple [mVpp]": round(1e3 * r.v_ripple_max_vpp, 1),
        "tol [%]": r.v_tol_pct,
        "fsw [kHz]": round(r.f_sw_hz / 1e3, 1) if r.f_sw_hz else "-",
    } for r in RAILS]

    tran_rows = [{
        "rail": r.name,
        "load step [A]": r.load_step_a,
        "slew [A/us]": r.load_step_slew_a_per_us,
        "max deviation [mV]": round(1e3 * r.v_deviation_max_v, 1),
        "settle within [us]": round(1e6 * r.settle_time_max_s, 1),
        "fc target [kHz]": round(r.f_cross_target_hz / 1e3, 1),
        "PM target [deg]": r.phase_margin_target_deg,
        "GM target [dB]": r.gain_margin_target_db,
    } for r in RAILS]

    return f"""# Specification

{GENERATED}

Generated from `simulation/smps/spec.py`, which is the only place any of these
numbers are written down.

## System

| item | value |
|---|---|
| Input voltage | {SYSTEM.vin_min_v:.0f} V to {SYSTEM.vin_max_v:.0f} V DC, nominal {SYSTEM.vin_nom_v:.0f} V |
| Survivable input excursion | {SYSTEM.vin_transient_max_v:.0f} V, non operating, clamping is external |
| Ambient | {SYSTEM.ambient_min_c:.0f} C to {SYSTEM.ambient_max_c:.0f} C |
| Cooling | {SYSTEM.cooling} |
| Useful output power | {useful_output_power_w():.2f} W at the connectors |
| Junction limit assumed | {T_J_MAX_C:.0f} C for every part |
| EMC reference envelope | {SYSTEM.emc_standard} |

## Rails

{_table(rail_rows)}
The current in "Iout total" includes downstream rails. The +5V stage feeds the
+3V3 buck and the +12V boost as well as its own connector load, and the +3V3
buck feeds the +1V8A LDO, so only the "at connector" column is available to a
user. `smps.losses.solve_power_tree` works this out rather than trusting a
hand written budget.

## Transient and loop targets

{_table(tran_rows)}
The +1V8A rail has a crossover target listed for completeness but it is not a
design input: the LDO's loop is inside a bought in part. What this design
controls there is the output capacitor, the preload and the input decoupling,
so the requirement on that rail is phase margin and supply rejection, not
bandwidth.

## Out of scope

* Input transient suppression beyond the {SYSTEM.vin_transient_max_v:.0f} V survivable level.
  Load dump clamping, if the end application needs it, is an external TVS.
* Reverse polarity beyond the series diode shown in the netlist.
* Isolation. Every rail shares one return.
* Common mode emissions. The pre-scan in this repository is differential mode
  only; see `docs/emc_prescan_method.md`.
* Any form of digital telemetry or sequencing control.

## Sequencing

The rails come up in power tree order because each one is fed by the one above
it. Nothing enforces a sequence beyond that, which is adequate for the loads
described and is called out here so that a user who needs a strict sequence
knows it is not provided.
"""


