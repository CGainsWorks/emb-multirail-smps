GENERATED = ("<!-- Generated by smps.report. Do not edit by hand; "
             "`make demo` overwrites this file. -->")


def _table(rows: list[dict], columns: list[str] | None = None) -> str:
    if not rows:
        return "_no rows_\n"
    cols = columns or list(rows[0].keys())
    out = ["| " + " | ".join(cols) + " |",
           "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out) + "\n"


