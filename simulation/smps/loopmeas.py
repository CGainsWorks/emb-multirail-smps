"""A virtual network analyser driven against the switching simulation.

This mirrors what a Bode 100 or a scope with a frequency response option does
on the bench. A small sinusoid is injected in series with the feedback divider,
the voltage either side of the injection is recorded, and the loop gain comes
out as ``T = -VA/VB``. Same injection point, same formula, so when the hardware
exists the bench sweep is directly comparable to the plots in
``test-results/bode/``.

Three details make the measurement clean:

*Commensurate frequencies.* Each sweep point is snapped to ``f = fsw * k/M``
for integers ``k`` and ``M``, and exactly ``M`` switching cycles are recorded.
The switching ripple is periodic at ``fsw``, so in a once-per-cycle sample
sequence it lands entirely on the DC bin and the discrete Fourier transform at
bin ``k`` rejects it exactly rather than approximately. No windowing, no
leakage, no averaging.

*Continuous injection.* The stimulus is generated by a two state oscillator
inside the simulated system, not by a value held constant across each switching
cycle. A held value is a zero order hold and would add ``exp(-s Tsw/2)`` of
phase lag to the measured loop gain that the real converter does not have. At
50 kHz on a 500 kHz converter that artefact is 18 degrees, which is the
difference between a comfortable design and a marginal one.

*Small signal.* The amplitude is a fraction of a percent of the output.
:func:`linearity_check` re-runs a point at double amplitude and reports how far
the answer moves, which is the same sanity check a careful bench measurement
does.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .switching import ConverterSim, SimConfig


@dataclass(frozen=True)
class SweepPoint:
    f_hz: float
    t: complex
    cycles: int
    periods: int


#: Highest measurable fraction of the switching frequency. Sampling once per
#: switching cycle puts the Nyquist limit at fsw/2, and the bin at exactly
#: fsw/2 is degenerate, so the sweep stops short of it. A bench analyser
#: triggered off the switching clock has the same limit for the same reason.
F_MAX_FRACTION = 0.45


def snap_commensurate(f_req: float, f_sw: float, periods: int = 8,
                      max_cycles: int = 400_000) -> tuple[float, int, int]:
    """Nearest ``fsw * k/M`` to ``f_req`` holding at least ``periods`` periods."""
    m = int(round(periods * f_sw / f_req))
    m = min(max(m, 4 * periods), max_cycles)
    k = max(int(round(f_req * m / f_sw)), 1)
    k = min(k, int(F_MAX_FRACTION * m))
    return f_sw * k / m, m, k


def measure_point(cfg: SimConfig, f_req: float, amp_v: float,
                  settle_cycles: int = 600, periods: int = 8) -> SweepPoint:
    f_act, m, k = snap_commensurate(f_req, cfg.f_sw, periods)
    sim = ConverterSim(cfg, inj_f_hz=f_act, inj_amp_v=amp_v)

    settle = max(settle_cycles, int(round(3 * cfg.f_sw / f_act)))
    u = np.array([cfg.v_in, 0.0, cfg.v_target])
    res = sim.run(settle + m, lambda _k: u, samples_per_interval=0,
                  inject_from_cycle=settle)

    va = res.v_a_cycle[settle:]
    vb = res.v_b_cycle[settle:]
    n = np.arange(m)
    w = np.exp(-2j * np.pi * k * n / m)
    return SweepPoint(f_act, -np.dot(va, w) / np.dot(vb, w), m, k)


def measure_loop(cfg: SimConfig, f_start: float, f_stop: float,
                 points: int = 20, amp_frac: float = 2e-3,
                 periods: int = 8) -> tuple[np.ndarray, np.ndarray]:
    """Stepped sine sweep of the closed loop gain."""
    amp = amp_frac * cfg.v_target
    f_stop = min(f_stop, F_MAX_FRACTION * cfg.f_sw)
    freqs = np.logspace(np.log10(f_start), np.log10(f_stop), points)
    out = [measure_point(cfg, f, amp, periods=periods) for f in freqs]
    f = np.array([p.f_hz for p in out])
    t = np.array([p.t for p in out])
    order = np.argsort(f)
    return f[order], t[order]


def linearity_check(cfg: SimConfig, f_hz: float, amp_frac: float = 2e-3) -> float:
    """Relative change in measured gain when the injection amplitude doubles."""
    a = measure_point(cfg, f_hz, amp_frac * cfg.v_target)
    b = measure_point(cfg, f_hz, 2 * amp_frac * cfg.v_target)
    return float(abs(b.t - a.t) / abs(a.t))
