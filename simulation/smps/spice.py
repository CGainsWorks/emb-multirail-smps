"""SPICE deck generation, in two dialects that are genuinely different.

The decks are generated from the same component values the Python models use,
so the two cannot drift apart.

``outputs/netlists/ngspice/``
    Strict ngspice. These are the ones CI actually executes, on every push,
    with the results compared against the Python models by
    ``scripts/run_ngspice.py``. ngspice is free, open source and the simulator
    inside KiCad, and it runs headless, which is the only reason a workflow can
    check it rather than a README claiming it.

``outputs/netlists/ltspice/``
    LTspice. Free to use and the de facto standard for switch mode supply work,
    but a Windows and Mac GUI with no package in any Linux distribution, so no
    runner can execute it. **These have never been run.** They are emitted
    because LTspice is where a vendor's own controller model would go once a
    part is chosen, and that is the next step this repository cannot take.

The two dialects are not interchangeable, which an earlier version of this file
claimed they were. ``Rser=`` on an inductor or capacitor, ``IF(a,b,c)`` and
``LIMIT(x,lo,hi)`` are all LTspice extensions that ngspice rejects. The ngspice
decks use explicit series resistors, a ternary and ``min(max(...))`` instead.
``tests/test_spice.py`` asserts that no LTspice-only token survives into an
ngspice deck, so the claim cannot rot back.
"""

from __future__ import annotations

from . import components as C
from . import design as D
from .emc import InputFilter
from .spec import rail


def _f(x: float) -> str:
    """SPICE friendly number. Plain decimal or exponent, never a unit suffix."""
    return f"{x:.6g}"


HEADER_NG = ("* Strict ngspice. Run: ngspice -b <file>\n"
             "* Generated by smps.spice. Do not edit; `make demo` overwrites it.\n")
HEADER_LT = ("* LTspice dialect. Open in LTspice, or run: LTspice -b <file>\n"
             "* Generated by smps.spice. Do not edit; `make demo` overwrites it.\n"
             "* NOT EXECUTED BY CI. No runner has an LTspice. See STATUS.md.\n")


# --------------------------------------------------------------------------
# Compensator AC decks
# --------------------------------------------------------------------------
# These are the strongest check available without hardware. The networks are
# passive components plus an ideal controlled source, so ngspice and the closed
# form in smps.compensation are solving the same linear system by different
# means and have to agree to numerical precision. If they do not, one of them
# is wrong, and historically it is not the one with a forty year test suite.

def type_ii_ac(name: str, ngspice: bool) -> str:
    comp = D.buck5_compensator() if name == "+5V" else D.boost12_compensator()
    div = D.BUCK5_DIVIDER if name == "+5V" else D.BOOST12_DIVIDER
    tag = name.replace("+", "").lower()
    head = HEADER_NG if ngspice else HEADER_LT
    # The transconductance source is wired non-inverting on purpose, so that
    # v(comp)/v(out) is +Kdiv*gm*Z and matches TypeII.response directly. The
    # inversion a real OTA provides is accounted for as negative feedback
    # everywhere else in this repository, not inside Gc.
    body = f"""* Type II compensation network, {name} rail
Vac   out 0 dc 0 ac 1
Rtop  out fb  {_f(div.r_top_ohm)}
Rbot  fb  0   {_f(div.r_bot_ohm)}
Gea   0 comp  fb 0 {_f(comp.gm_s)}
Ro    comp 0  {_f(comp.ro_ohm)}
Rc    comp nc {_f(comp.rc_ohm)}
Cc    nc   0  {_f(comp.cc_f)}
Cp    comp 0  {_f(comp.cp_f)}
"""
    if ngspice:
        body += f""".control
ac dec 25 1 10meg
wrdata typeii_{tag}.dat v(comp)
quit
.endc
.end
"""
    else:
        body += ".ac dec 25 1 10meg\n.end\n"
    return head + body


def type_iii_ac(ngspice: bool) -> str:
    c = D.buck3v3_compensator()
    head = HEADER_NG if ngspice else HEADER_LT
    # Physical wiring: the amplifier inverts, so v(comp)/v(out) is -Zf/Zi.
    # scripts/run_ngspice.py compares against -TypeIII.response for that
    # reason, and says so.
    body = f"""* Type III compensation network, +3V3 rail
Vac   out 0 dc 0 ac 1
R1    out fb  {_f(c.r1_ohm)}
Rbot  fb  0   {_f(c.rbot_ohm)}
R3    out n3  {_f(c.r3_ohm)}
Cf3   n3  fb  {_f(c.cf3_f)}
Rf    comp nf {_f(c.rf_ohm)}
Cf1   nf  fb  {_f(c.cf1_f)}
Cf2   comp fb {_f(c.cf2_f)}
Eea   comp 0  0 fb 1e6
"""
    if ngspice:
        body += """.control
ac dec 25 1 10meg
wrdata typeiii_3v3.dat v(comp)
quit
.endc
.end
"""
    else:
        body += ".ac dec 25 1 10meg\n.end\n"
    return head + body


# --------------------------------------------------------------------------
# Input filter
# --------------------------------------------------------------------------

def input_filter_ac(ngspice: bool) -> str:
    f = InputFilter()
    head = HEADER_NG if ngspice else HEADER_LT
    if ngspice:
        # No Rser= or Lser=: ngspice does not have them, so the parasitics are
        # explicit components. This is also the more honest schematic.
        body = f"""* Differential mode input filter into a 50 ohm / 5 uH LISN
Iconv conv 0 dc 0 ac 1
C1    conv c1a {_f(f.c1_f)}
L1esl c1a  c1b {_f(f.c1_esl_h)}
R1esr c1b  0   {_f(f.c1_esr_ohm)}
Cb    conv cba {_f(f.cbulk_f)}
Lbesl cba  cbb {_f(f.cbulk_esl_h)}
Rbesr cbb  0   {_f(f.cbulk_esr_ohm)}
Ldm   conv ldm {_f(f.l_dm_h)}
Rdm   ldm  lead {_f(f.l_dm_esr_ohm)}
C2    lead c2a {_f(f.c2_f)}
L2esl c2a  c2b {_f(f.c2_esl_h)}
R2esr c2b  0   {_f(f.c2_esr_ohm)}
Llisn lead lisn {_f(f.lisn_l_h)}
Rlisn lisn 0   {_f(f.lisn_r_ohm)}
.control
ac dec 25 10k 30meg
wrdata input_filter.dat v(lisn)
quit
.endc
.end
"""
    else:
        body = f"""* Differential mode input filter into a 50 ohm / 5 uH LISN
Iconv conv 0 AC 1
C1    conv 0 {_f(f.c1_f)} Rser={_f(f.c1_esr_ohm)} Lser={_f(f.c1_esl_h)}
Cbulk conv 0 {_f(f.cbulk_f)} Rser={_f(f.cbulk_esr_ohm)} Lser={_f(f.cbulk_esl_h)}
Ldm   conv lead {_f(f.l_dm_h)} Rser={_f(f.l_dm_esr_ohm)}
C2    lead 0 {_f(f.c2_f)} Rser={_f(f.c2_esr_ohm)} Lser={_f(f.c2_esl_h)}
Llisn lead lisn {_f(f.lisn_l_h)}
Rlisn lisn 0 {_f(f.lisn_r_ohm)}
.ac dec 25 10k 30meg
.end
"""
    return head + body


# --------------------------------------------------------------------------
# Switching transient, voltage mode buck
# --------------------------------------------------------------------------
# Emitted as a full switching deck because a voltage mode trailing edge
# modulator is completely defined by a sawtooth and a comparator, so the deck
# is an honest model of the circuit rather than a guess at somebody's silicon.
# There is deliberately no switching deck for the two peak current mode rails:
# a peak current modulator is a comparator, a latch, an artificial ramp and a
# blanking window, and the numbers that matter live inside a controller that
# has not been selected. An invented version would run, look convincing and
# validate nothing.

def buck3v3_transient(ngspice: bool) -> str:
    p = C.BUCK3V3
    r = rail("+3V3")
    c = D.buck3v3_compensator()
    ts = 1.0 / r.f_sw_hz
    v_in = rail("+5V").v_out_v
    i_out = 3.0
    r_load = r.v_out_v / i_out
    head = HEADER_NG if ngspice else HEADER_LT

    common = f"""* +3V3 synchronous buck, voltage mode, Type III compensation
Vin   vin 0 {_f(v_in)}
Rload out 0 {_f(r_load)}
Shs   vin sw   gate 0 swhs
Sls   sw  0    gateb 0 swls
"""
    if ngspice:
        body = common + f"""Bgb   gateb 0 V = 1 - V(gate)
L1    sw  lx {_f(p['L_H'])}
Rl1   lx  out {_f(p['L_dcr_ohm'])}
Cout  out cx {_f(p['Cout_F'])}
Resr  cx  0  {_f(p['Cout_esr_ohm'])}
Cin   vin ci {_f(p['Cin_F'])}
Rcin  ci  0  {_f(p['Cin_esr_ohm'])}
Vramp ramp 0 PULSE(0 {_f(p['v_ramp_vpp'])} 0 {_f(ts * 0.98)} {_f(ts * 0.02)} 1n {_f(ts)})
Bpwm  gate 0 V = min(max(0.5 + 1000*(V(comp) - V(ramp)), 0), 1)
R1    out fb {_f(c.r1_ohm)}
Rbot  fb  0  {_f(c.rbot_ohm)}
R3    out n3 {_f(c.r3_ohm)}
Cf3   n3  fb {_f(c.cf3_f)}
Rf    comp nf {_f(c.rf_ohm)}
Cf1   nf  fb {_f(c.cf1_f)}
Cf2   comp fb {_f(c.cf2_f)}
Bea   comp 0 V = min(max(1e5 * ({_f(p['v_ref_v'])} - V(fb)), 0), {_f(p['v_ramp_vpp'])})
* Separate models, because the two devices do not have the same Rds(on) and
* using one model for both was quietly putting the high side figure on the low
* side as well.
.model swhs sw(ron={_f(p['rds_hs_ohm'])} roff=1meg vt=0.5 vh=0.1)
.model swls sw(ron={_f(p['rds_ls_ohm'])} roff=1meg vt=0.5 vh=0.1)
* Switching circuits are where a general purpose solver earns its reputation
* for not converging, and this deck took three attempts.
*
* An infinitely sharp comparator fails outright. A tanh instead fails
* differently and more interestingly: it saturates, so its derivative vanishes,
* Newton is left with no gradient to follow and the gate node runs away to a
* thousand volts. What works is a comparator that is linear across a narrow
* band and hard limited outside it, so the Jacobian is finite where it matters
* and the output cannot leave [0, 1] however badly an iteration misbehaves.
* The band is 1 mV wide, which at this ramp slope is one nanosecond.
*
* Hysteresis on the switches, Gear integration and a hundred time points per
* switching period do the rest.
.options method=gear maxord=2 reltol=1e-3 abstol=1e-10 vntol=1e-6 itl4=200
.control
tran {_f(ts / 200)} 1m 0.9m {_f(ts / 100)}
meas tran vavg AVG v(out) from=0.95m to=1m
meas tran vmax MAX v(out) from=0.95m to=1m
meas tran vmin MIN v(out) from=0.95m to=1m
quit
.endc
.end
"""
    else:
        body = common + f"""Bgb   gateb 0 V=1-V(gate)
L1    sw  out {_f(p['L_H'])} Rser={_f(p['L_dcr_ohm'])}
Cout  out cx {_f(p['Cout_F'])}
Resr  cx  0  {_f(p['Cout_esr_ohm'])}
Cin   vin 0  {_f(p['Cin_F'])} Rser={_f(p['Cin_esr_ohm'])}
Vramp ramp 0 PULSE(0 {_f(p['v_ramp_vpp'])} 0 {_f(ts * 0.98)} {_f(ts * 0.02)} 1n {_f(ts)})
Bpwm  gate 0 V=IF(V(comp)>V(ramp),1,0)
R1    out fb {_f(c.r1_ohm)}
Rbot  fb  0  {_f(c.rbot_ohm)}
R3    out n3 {_f(c.r3_ohm)}
Cf3   n3  fb {_f(c.cf3_f)}
Rf    comp nf {_f(c.rf_ohm)}
Cf1   nf  fb {_f(c.cf1_f)}
Cf2   comp fb {_f(c.cf2_f)}
Bea   comp 0 V=LIMIT({_f(p['v_ref_v'])}*1e5-V(fb)*1e5, 0, {_f(p['v_ramp_vpp'])})
.model SWMOD SW(Ron={_f(p['rds_hs_ohm'])} Roff=1Meg Vt=0.5 Vh=0)
.tran {_f(ts / 100)} 2m 1.5m {_f(ts / 50)}
.end
"""
    return head + body


