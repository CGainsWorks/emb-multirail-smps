def ngspice_decks() -> dict[str, str]:
    return {
        "comp_buck5_typeii_ac.cir": type_ii_ac("+5V", True),
        "comp_boost12_typeii_ac.cir": type_ii_ac("+12V", True),
        "comp_buck3v3_typeiii_ac.cir": type_iii_ac(True),
        "input_filter_ac.cir": input_filter_ac(True),
        "buck3v3_transient.cir": buck3v3_transient(True),
    }


def ltspice_decks() -> dict[str, str]:
    return {
        "comp_buck5_typeii_ac.cir": type_ii_ac("+5V", False),
        "comp_boost12_typeii_ac.cir": type_ii_ac("+12V", False),
        "comp_buck3v3_typeiii_ac.cir": type_iii_ac(False),
        "input_filter_ac.cir": input_filter_ac(False),
        "buck3v3_transient.cir": buck3v3_transient(False),
    }


